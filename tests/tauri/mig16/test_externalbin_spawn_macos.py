# ─── Test 1: tauri.conf.json externalBin list ──────────────────────────


def test_tauri_conf_external_bin_lists_python_sidecar(tauri_conf) -> None:
    """ADR-0020 §4.1 + §7: externalBin must list ``bin/python-sidecar``.

    Tauri v2's ``externalBin`` mechanism appends the Rust target triple
    at runtime, so the JSON entry is the binary base name (no triple
    suffix, no ``.exe``). On macOS the shipped binaries on disk are
    ``src-tauri/bin/python-sidecar-aarch64-apple-darwin`` (Apple Silicon)
    and ``src-tauri/bin/python-sidecar-x86_64-apple-darwin`` (Intel) —
    Tauri picks the right one at runtime via
    ``std::env::consts::ARCH`` + ``std::env::consts::OS``.
    """
    bundle = tauri_conf.get("bundle", {})
    assert "externalBin" in bundle, "bundle.externalBin must exist"
    external_bin = bundle["externalBin"]
    assert isinstance(external_bin, list), "externalBin must be a list"
    assert "bin/python-sidecar" in external_bin, (
        "externalBin must contain 'bin/python-sidecar' (Tauri appends the target triple at spawn time)"
    )
    # The list must NOT contain any triple-suffixed entries — the base
    # name is what the Rust `app.shell().sidecar("python-sidecar")` call
    # in spawn.rs uses, and Tauri internally appends the triple.
    for entry in external_bin:
        assert not re.search(
            r"-x86_64-apple-darwin"
            r"|-aarch64-apple-darwin"
            r"|-x86_64-pc-windows-msvc"
            r"|-aarch64-pc-windows-msvc"
            r"|-x86_64-unknown-linux-gnu"
            r"|-aarch64-unknown-linux-gnu",
            entry,
        ), (
            f"externalBin entry '{entry}' must NOT contain the target "
            f"triple — Tauri appends it at runtime. Use the base name "
            f"only (e.g. 'bin/python-sidecar')."
        )


def test_tauri_conf_shell_scope_allows_python_sidecar(tauri_conf) -> None:
    """ADR-0020 §7: the shell capability must scope spawn to the sidecar.

    Tauri v2 rejects an unconstrained ``shell:allow-spawn``; the
    capability must name the sidecar binary by its base name. This is
    the same on macOS as on Windows — Tauri's shell plugin is
    cross-platform.
    """
    shell = tauri_conf.get("plugins", {}).get("shell", {})
    assert shell.get("sidecar") is True, "plugins.shell.sidecar must be true to enable the externalBin API"
    scope = shell.get("scope", [])
    assert isinstance(scope, list) and scope, "plugins.shell.scope must be a non-empty list"
    # At least one scope entry must name bin/python-sidecar with sidecar=true.
    matches = [s for s in scope if s.get("name") == "bin/python-sidecar" and s.get("sidecar") is True]
    assert matches, (
        "plugins.shell.scope must include "
        "{'name': 'bin/python-sidecar', 'sidecar': true} "
        "(Tauri v2 requires explicit spawn scoping)"
    )


