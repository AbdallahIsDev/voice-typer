# ─── Test 8: no real process spawn (mocked AppHandle/ShellExt) ────────


def test_this_test_file_does_not_spawn_processes() -> None:
    """This test file must NOT spawn any real process.

    The Tauri ``AppHandle`` / ``tauri_plugin_shell::ShellExt`` APIs
    are mocked by treating them as opaque: the tests above only read
    the Rust source code as text and assert on its contents. No
    ``subprocess.Popen``, ``os.exec*``, ``os.system``, ``os.spawn*``,
    or ``tauri::AppHandle`` is constructed at runtime.

    We use ``ast`` to parse this file and assert no ``Call`` node
    invokes any forbidden process-spawning API. (String literals in
    docstrings / forbidden_apis lists are NOT calls — the AST check
    avoids false positives on the docstring examples above.)
    """
    import ast

    this_source = _THIS_FILE.read_text(encoding="utf-8")
    tree = ast.parse(this_source)

    forbidden_call_names = {
        ("subprocess", "Popen"),
        ("subprocess", "run"),
        ("subprocess", "call"),
        ("subprocess", "check_call"),
        ("subprocess", "check_output"),
        ("os", "system"),
        ("os", "popen"),
        ("os", "spawnl"),
        ("os", "spawnle"),
        ("os", "spawnlp"),
        ("os", "spawnlpe"),
        ("os", "spawnv"),
        ("os", "spawnve"),
        ("os", "spawnvp"),
        ("os", "spawnvpe"),
        ("os", "execl"),
        ("os", "execle"),
        ("os", "execlp"),
        ("os", "execlpe"),
        ("os", "execv"),
        ("os", "execve"),
        ("os", "execvp"),
        ("os", "execvpe"),
    }

    def _qualified(node: ast.AST) -> tuple[str, ...] | None:
        """Return the dotted call target of `node`, or None."""
        if isinstance(node, ast.Attribute):
            base = _qualified(node.value)
            if base is None:
                return None
            return base + (node.attr,)
        if isinstance(node, ast.Name):
            return (node.id,)
        return None

    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        target = _qualified(node.func)
        if target is None:
            continue
        for forbidden in forbidden_call_names:
            if tuple(target[-len(forbidden) :]) == forbidden:
                pytest.fail(
                    f"This test file must NOT call {'.'.join(forbidden)}() — "
                    f"the tauri::AppHandle / tauri_plugin_shell APIs are "
                    f"mocked by static source inspection. No real sidecar "
                    f"process may be spawned in the sandbox."
                )


