"""MIG-1.6 Phase 0-M Gate Check 2 — externalBin spawn validation (macOS).

This module is gate check 2 of 9 for Phase 0-M (the macOS Tauri cutover
gate). It validates the Tauri sidecar spawn path that the Rust host uses
to launch the frozen Python sidecar via Tauri's ``externalBin`` mechanism
on **both** macOS archs (Apple Silicon + Intel).

Scope of this check (ADR-0020 §1 + §4.1 + §7 + §10 + §13.2 + §14):

1. ``tauri.conf.json`` declares ``externalBin: ["bin/python-sidecar"]``
   (Tauri appends the Rust target triple at runtime — see ADR-0020 §7
   "externalBin per-arch naming" + §4.1). The shipped binaries on disk
   are ``src-tauri/bin/python-sidecar-x86_64-apple-darwin`` (Intel) and
   ``src-tauri/bin/python-sidecar-aarch64-apple-darwin`` (Apple Silicon).

2. ``tauri.conf.json`` ships the macOS native binary
   (``macos-key-listener``, built by ``scripts/build/compile_native.sh``
   via ``swiftc -O``) and the macOS prewarm binaries for both
   ``x86_64-apple-darwin`` + ``aarch64-apple-darwin`` target triples as
   ``bundle.resources``. Per ADR-0020 §5, the prewarm helper is a
   ``bundle.resource`` (NOT ``externalBin``) because it is launched by
   the macOS LaunchAgent, NOT spawned by Tauri.

3. ``src-tauri/src/sidecar/spawn.rs`` reads the ``server_started`` JSON
   line from the sidecar's stdout via ``tauri_plugin_shell``'s
   ``CommandEvent::Stdout`` stream and parses the port. (The auth token
   is generated by the Rust host and passed to the sidecar via the
   ``VOICE_TYPER_IPC_TOKEN`` env var at spawn — it is NOT echoed back
   in the ``server_started`` payload. See ADR-0020 §3 + §1.)

4. The release-path spawn (``spawn_sidecar_release``) is **cross-platform**
   — it calls ``app.shell().sidecar("python-sidecar")`` which goes
   through Tauri's shell plugin. There is NO ``cfg!(target_os = "macos")``
   branch in the release spawn path: macOS uses the **same spawn code**
   as Windows + Linux. (The dev-mode path in ``spawn_sidecar_dev_mode``
   DOES use ``cfg!(target_os = "windows")`` to pick ``python.exe`` vs
   ``python3``, and ``prewarm_resource_path`` uses ``cfg!(windows)`` for
   the ``.exe`` suffix — those are NOT the release spawn path.)

5. The FT-1 crash supervisor (in ``src-tauri/src/sidecar/ft1.rs``, backed
   by constants in ``src-tauri/src/util.rs``) restarts the sidecar on
   crash with a doubling backoff schedule
   ``[500ms, 1s, 2s, 4s, 8s]`` (task's "500ms → 8s" range) and a cap of
   5 retries before falling back to a full-app ``app.restart()``
   (ADR-0020 §10). The schedule length equals the cap.

6. The sidecar binds ``127.0.0.1:0`` (loopback + ephemeral port) and
   writes the OS-assigned port to stdout — the host NEVER chooses a
   fixed port. (ADR-0020 §1 "Ephemeral port — locked bind direction".)

7. The tests in this file do NOT spawn any real process — they read
   the Rust source files + JSON config as text and assert on their
   contents. No ``subprocess.Popen`` / ``os.exec*`` /
   ``tauri::AppHandle`` is constructed. The ``tauri::AppHandle`` /
   ``tauri_plugin_shell::ShellExt`` APIs are mocked by treating them
   as opaque — we only verify the source code wires them correctly.

VALIDATE ON MACOS HOST:
    This file is the Linux-sandbox half of gate check 2. The other
    half MUST be executed by a human on a real macOS host (BOTH Apple
    Silicon AND Intel) — ADR-0020 §6 / runbook §6.1. Steps:

    1. Build sidecar (see check 1) for the host arch
       (``python-sidecar-aarch64-apple-darwin`` on Apple Silicon,
        ``python-sidecar-x86_64-apple-darwin`` on Intel).
    2. ``cd src-tauri; cargo tauri build --target x86_64-apple-darwin``
       (OR ``aarch64-apple-darwin``; OR ``universal-apple-darwin`` for
       a universal .app that ships both arches).
    3. Open ``target/<arch>/release/bundle/dmg/*.dmg`` → drag to
       Applications (or ``hdiutil attach`` + ``cp -R`` to script it).
    4. Launch "Voice Typer" from Applications (first launch will prompt
       for Accessibility + Microphone permission — grant both via
       System Settings → Privacy & Security).
    5. Within 30 s, check
       ``~/Library/Logs/voice-typer/voice-typer.log`` for:
       - ``[SIDECAR] server_started port=XXXXX``
         (where XXXXX is an OS-assigned ephemeral port, e.g. 51234)
       - ``[SIDECAR-WS] listening on 127.0.0.1:XXXXX`` (sidecar log)
    6. ``ps aux | grep python-sidecar`` — must show the sidecar process
       matching the host arch (``python-sidecar-aarch64-apple-darwin``
       on Apple Silicon, ``python-sidecar-x86_64-apple-darwin`` on
       Intel).
    Expected: sidecar spawns within 2 s; log shows ``server_started``
    with an ephemeral port (1024-65535, NOT a fixed port like 9876).
    Fail scenarios:
      - ``failed to resolve sidecar binary`` → the host-arch
        ``python-sidecar-<arch>-apple-darwin`` is missing from
        ``src-tauri/bin/`` (run §1 of the runbook for the missing arch).
      - ``sidecar did not emit server_started within 30000ms`` →
        sidecar crashed on import (CTranslate2 wheel ABI mismatch on
        aarch64, or stdout block-buffered under Tauri's pipe).
      - macOS Gatekeeper blocks the .app → run
        ``xattr -dr com.apple.quarantine "/Applications/Voice Typer.app"``
        for local dev, OR sign + notarize per runbook §7.

    See ``docs/migration/macos-validation-runbook.md`` §5 (gate point 1)
    + §6.1 (gate point 2) for the full pass criteria + fail-scenario
    triage.

References:
- ADR-0020 §1 — ephemeral port + locked bind direction + the
  ``server_started`` stdout handshake.
- ADR-0020 §4.1 — per-arch ``externalBin`` binary naming (Tauri appends
  the Rust target triple at runtime via ``std::env::consts::ARCH`` +
  ``std::env::consts::OS``).
- ADR-0020 §5 — prewarm is a ``bundle.resource`` (NOT ``externalBin``)
  because it is launched by the macOS LaunchAgent, not by Tauri.
- ADR-0020 §7 — Tauri config + capabilities + ``externalBin`` list.
- ADR-0020 §10 — FT-1 supervisor backoff schedule + cap (5 retries,
  doubling 500ms → 8s, then ``app.restart()``).
- ADR-0020 §13.2 — macOS code-signing + notarization (out of scope for
  this spawn-path check, but the gate points downstream depend on it).
- ADR-0020 §14 — dev-mode spawn fallback (out of scope for this macOS
  release-path check, but verified as a code path).
- runbook §5 (gate point 1) — host-side validation commands for the
  externalBin spawn.
- runbook §6.1 (gate point 2) — WS + HMAC handshake validation.
"""

