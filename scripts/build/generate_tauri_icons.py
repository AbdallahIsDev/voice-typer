"""Regenerate the committed Tauri icon set from the app logo (repeatable).

``src-tauri/icons/*`` are REAL committed files, regenerated with
``tauri icon`` from ``voice_typer/client/scripts/logo.svg`` (the app's
logo source of truth — edit that file to change the icon). This script
makes the regeneration repeatable and self-validating in one command:

1. **Regenerate** — runs ``npx @tauri-apps/cli icon`` against the logo.
   Output lands in ``src-tauri/icons/`` (the default directory next to
   ``tauri.conf.json``; passed explicitly for determinism).

2. **Prune** — ``tauri icon`` emits a superset (``64x64.png``,
   ``Square*Logo.png``, ``StoreLogo.png``, ``android/``, ``ios/``, ...).
   This script deletes everything under ``src-tauri/icons/`` EXCEPT the
   ``bundle.icon`` set — read from ``tauri.conf.json``, the single
   source of truth — and the ``tray/`` dir (the Tauri tray state
   icons, generated separately by ``generate_tray_icons.py``).
   Re-running after a ``logo.svg`` change therefore always re-prunes
   to the exact 6 bundle icons.

3. **Refresh the drift guard** — runs the config ↔ git icon lockstep
   tests (``test_tauri_conf_icon_list_matches_tracked_icons`` +
   ``test_per_arch_configs_do_not_override_bundle_icon``) so a prune
   miss or a future ``tauri icon`` change that alters the icon SET
   fails immediately instead of on the next CI run. The tests are
   dynamic (config ↔ ``git ls-files``), so no test editing is ever
   needed after a regeneration.

Note: this is the TAURI icon pipeline. The legacy PyInstaller/Inno
microphone ICO lives in ``scripts/build/generate_icon.py`` (DEAD-015) —
a different artifact for a different (legacy) pipeline; do not merge
them.

Usage:
    python scripts/build/generate_tauri_icons.py          # regen + commit workflow
    python scripts/build/generate_tauri_icons.py --check  # CI drift check (never writes)
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SRC_TAURI = PROJECT_ROOT / "src-tauri"
ICONS_DIR = SRC_TAURI / "icons"
TAURI_CONF = SRC_TAURI / "tauri.conf.json"
LOGO = PROJECT_ROOT / "voice_typer" / "client" / "scripts" / "logo.svg"

# Directories under src-tauri/icons/ that are preserved by the prune
# even though they are not in bundle.icon (tray/ — the Tauri tray
# state icons, generated by generate_tray_icons.py and guarded by
# tests/tauri/test_tray_icons.py).
PRESERVE_DIRS = {"tray"}

# The @tauri-apps/cli version the icon pipeline is pinned to. The CLI
# is NOT a package.json dependency — it is fetched on demand via
# `npx --yes` — so without a pin here every new CLI release silently
# changes the PNG bytes (2026-08-17: a CLI bump dropped the pHYs chunk
# the Aug-15 commit had stripped and re-encoded IDAT, failing the
# `--check` drift gate). Pinning keeps `tauri icon` output
# deterministic; bump this deliberately + regenerate + commit.
TAURI_CLI_PIN = "2.11.4"

# The drift-guard tests re-run after every regeneration: the config ↔
# git lockstep guards PLUS the dimension validation (a ``tauri icon``
# regen that emits a wrong-sized PNG must fail the refresh immediately).
DRIFT_TEST_NODES = (
    "tests/tauri/test_gen_tauri_icons_stub.py::test_tauri_conf_icon_list_matches_tracked_icons "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_per_arch_configs_do_not_override_bundle_icon "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_generated_pngs_have_valid_signature_and_ihdr "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_bundle_icon_pngs_match_dimension_table "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_committed_pngs_have_real_tauri_icon_container_layout "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_committed_ico_matches_real_tauri_icon_container "
    "tests/tauri/test_gen_tauri_icons_stub.py::test_committed_icns_matches_real_tauri_icon_container"
)


def bundle_icon_paths(config_path: Path = TAURI_CONF) -> set[str]:
    """The ``bundle.icon`` list (src-tauri-relative) — the prune keep-set.

    ``tauri.conf.json`` is the single source of truth for which icons
    ship in the bundle; the drift guard enforces the same set against
    git, so reading it here keeps the prune and the guard in lockstep.
    """
    data = json.loads(config_path.read_text(encoding="utf-8"))
    return set(data["bundle"]["icon"])


def run_tauri_icon(logo: Path = LOGO, icons_dir: Path = ICONS_DIR) -> None:
    """Regenerate the full icon set into ``icons_dir`` via ``tauri icon``.

    ``tauri icon`` never deletes stale files, so the caller must prune
    afterwards (see :func:`prune_icons_dir`).
    """
    if not logo.is_file():
        sys.exit(f"logo source not found: {logo} — edit this file to change the icon.")
    npx = shutil.which("npx")
    if npx is None:
        sys.exit("npx not found on PATH — install Node.js (npx) to regenerate icons.")
    base = [npx, "--yes", f"@tauri-apps/cli@{TAURI_CLI_PIN}", "icon", str(logo), "-o", str(icons_dir)]
    # On Windows `npx` is a .cmd shim that CreateProcess cannot exec
    # directly (WinError 2); route it through cmd.exe there, keep the
    # direct exec on POSIX.
    cmd: list[str] = ["cmd", "/c", *base] if os.name == "nt" else base
    result = subprocess.run(cmd, cwd=str(PROJECT_ROOT), capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"`tauri icon` failed (exit {result.returncode}):\n{result.stdout}\n{result.stderr}")
    print(result.stdout.strip())


def prune_icons_dir(
    icons_dir: Path,
    keep: set[str],
    preserve_dirs: set[str] = PRESERVE_DIRS,
) -> list[str]:
    """Delete everything under ``icons_dir`` except the ``keep`` set.

    ``keep`` entries are src-tauri-relative (``icons/<name>``); only
    top-level entries are expected (all 6 bundle icons are top-level).
    Directories in ``preserve_dirs`` are left untouched. Returns the
    list of pruned entry names (for reporting).
    """
    pruned: list[str] = []
    for entry in sorted(icons_dir.iterdir()):
        if entry.name in preserve_dirs:
            continue
        if f"icons/{entry.name}" in keep:
            continue
        if entry.is_dir():
            # tauri icon's android/ios/ trees are nested — remove
            # recursively (tray/ and the keep-set entries are never dirs
            # here, so this cannot touch them).
            shutil.rmtree(entry)
        else:
            entry.unlink()
        pruned.append(entry.name)
    return pruned


def validate_icon_set(
    icons_dir: Path,
    keep: set[str],
    preserve_dirs: set[str] = PRESERVE_DIRS,
) -> tuple[list[str], list[str]]:
    """Return ``(missing, extra)`` for the on-disk set vs the keep-set.

    ``missing`` = bundle.icon entries with no file on disk after regen
    (a future ``tauri icon`` change could drop a required icon).
    ``extra`` = files on disk not in bundle.icon (a prune miss).
    """
    keep_names = {p.removeprefix("icons/") for p in keep}
    on_disk = {e.name for e in icons_dir.iterdir() if e.name not in preserve_dirs and (e.is_file() or e.is_dir())}
    missing = sorted(keep_names - on_disk)
    extra = sorted(on_disk - keep_names)
    return missing, extra


def refresh_drift_guard(root: Path = PROJECT_ROOT) -> None:
    """Re-run the config ↔ git icon lockstep tests (exit non-zero on drift).

    The drift tests are dynamic (``bundle.icon`` ↔ ``git ls-files``),
    so "refreshing" them is a matter of RUNNING them — no fixture or
    expected-set edit is needed after a regeneration. Note: the icons
    test module's autouse fixture runs ``gen_tauri_icons_stub.py
    --clean`` afterwards (removes binary stubs, never icons); callers
    that need the stubs restored should re-run the stub generator.
    """
    cmd = [
        sys.executable,
        "-m",
        "pytest",
        "-q",
        "--no-cov",
        *DRIFT_TEST_NODES.split(),
    ]
    result = subprocess.run(cmd, cwd=str(root), capture_output=True, text=True)
    print(result.stdout.strip())
    if result.returncode != 0:
        sys.exit(
            "icon drift guard FAILED after regeneration — the icon SET is not "
            "in lockstep with tauri.conf.json / git:\n"
            f"{result.stdout}\n{result.stderr}"
        )


def restore_binary_stubs_if_missing(root: Path = PROJECT_ROOT) -> None:
    """Restore the binary stubs the drift-test cleanup may have removed.

    Mirrors the CI idiom ``--check || generate``: if the stub set is
    intact this is a no-op; otherwise it regenerates the missing
    sidecar / prewarm / native stubs so ``cargo tauri build`` dry-runs
    still succeed on a clean checkout.
    """
    stub_script = root / "scripts" / "gen_tauri_icons_stub.py"
    check = subprocess.run(
        [sys.executable, str(stub_script), "--check"],
        cwd=str(root),
        capture_output=True,
        text=True,
    )
    if check.returncode != 0:
        subprocess.run([sys.executable, str(stub_script)], cwd=str(root), check=True)
        print("Restored missing binary stubs (drift-test cleanup removed them).")


def _load_icns_validator():
    """Lazy-import ``_validate_icns`` from ``scripts/gen_tauri_icons_stub.py``.

    That script owns the canonical ICNS structural validator (magic +
    chunk table + per-OSType PNG IHDR dimensions) used by the
    ``--check-icons`` CI gate. Importing it keeps ONE implementation for
    structure; the stub script's module-level code is constants-only.
    """
    import importlib.util

    stub = PROJECT_ROOT / "scripts" / "gen_tauri_icons_stub.py"
    spec = importlib.util.spec_from_file_location("_vt_gen_tauri_icons_stub", stub)
    assert spec is not None and spec.loader is not None, f"cannot load {stub}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module._validate_icns


def compare_icon_trees(
    regen_dir: Path,
    committed_dir: Path,
    keep: set[str],
    preserve_dirs: set[str] = PRESERVE_DIRS,
    icns_validator=None,
) -> list[str]:
    """Return drift problems comparing a fresh regen (already pruned) vs committed.

    Byte-comparison is used for every deterministic artifact — the 4
    PNGs + ``icon.ico`` (verified byte-stable across back-to-back
    ``tauri icon`` runs with the same CLI + logo). ``icon.icns`` is NOT
    byte-deterministic (the ``image`` crate emits different chunk order
    + per-chunk compression on every run — verified empirically), so it
    is compared STRUCTURALLY instead: both sides must be valid ICNS
    containers (``icns_validator``, defaulting to the stub script's
    ``_validate_icns``). The preserved dirs (``tray/``) are excluded —
    they belong to a separate pipeline.
    """
    if icns_validator is None:
        icns_validator = _load_icns_validator()

    def names(d: Path) -> set[str]:
        return {e.name for e in d.iterdir() if e.name not in preserve_dirs}

    problems: list[str] = []
    regen_names = names(regen_dir)
    committed_names = names(committed_dir)

    missing = sorted(committed_names - regen_names)
    if missing:
        problems.append(f"missing from regenerated set: {missing}")
    extra = sorted(regen_names - committed_names)
    if extra:
        problems.append(f"present in regenerated set but not committed: {extra}")

    for name in sorted(committed_names & regen_names):
        regen_file = regen_dir / name
        committed_file = committed_dir / name
        if name == "icon.icns":
            # Non-deterministic output (see docstring): validate both
            # sides structurally instead of byte-comparing.
            for label, f in (("regenerated", regen_file), ("committed", committed_file)):
                for problem in icns_validator(f):
                    problems.append(f"icon.icns ({label}): {problem}")
            continue
        if regen_file.read_bytes() != committed_file.read_bytes():
            problems.append(
                f"{name} differs from a fresh `tauri icon` + prune output — "
                "run `python scripts/build/generate_tauri_icons.py` and commit "
                "the result"
            )
    return problems


def check_committed_icons(root: Path = PROJECT_ROOT) -> int:
    """Exit 0 iff the committed ``src-tauri/icons`` matches a fresh regen + prune.

    CI drift check (``--check``): regenerates into a TEMP dir (the real
    tree is never touched — nothing is pruned or overwritten), prunes
    with the exact same logic ``main()`` uses, and compares against the
    committed icons. Exits 1 on any drift (missing/extra file, changed
    bytes, structurally invalid ICNS) so the CI step fails and the
    maintainer regenerates + commits.
    """
    keep = bundle_icon_paths()
    with tempfile.TemporaryDirectory(prefix="vt-icons-check-") as tmp:
        regen_dir = Path(tmp) / "icons"
        regen_dir.mkdir()
        run_tauri_icon(LOGO, regen_dir)
        prune_icons_dir(regen_dir, keep)
        problems = compare_icon_trees(regen_dir, ICONS_DIR, keep)
    if problems:
        print(
            "icon drift detected: committed src-tauri/icons does not match a fresh `tauri icon` + prune output:",
            file=sys.stderr,
        )
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print(
            "Fix: run `python scripts/build/generate_tauri_icons.py` and commit the regenerated icons.",
            file=sys.stderr,
        )
        return 1
    print(f"OK: committed src-tauri/icons matches a fresh `tauri icon` + prune ({len(keep)} icons).")
    return 0


def main() -> None:
    keep = bundle_icon_paths()
    run_tauri_icon()
    pruned = prune_icons_dir(ICONS_DIR, keep)
    if pruned:
        print(f"Pruned {len(pruned)} non-bundle icon(s): {', '.join(pruned)}")
    missing, extra = validate_icon_set(ICONS_DIR, keep)
    problems = []
    if missing:
        problems.append(f"missing on disk: {missing}")
    if extra:
        problems.append(f"not in bundle.icon: {extra}")
    if problems:
        sys.exit("icon set validation failed after regeneration — " + "; ".join(problems))
    print(f"Icon set OK: exactly {len(keep)} bundle.icon files under src-tauri/icons/.")
    # Snapshot the fresh regen BEFORE the drift guard: the icons test
    # module's autouse ``_serialize_and_cleanup`` fixture restores every
    # committed icon to its git bytes before/after each test, so without
    # this the guard silently reverts the working tree to the OLD icons
    # and there is nothing to commit (the ``--check`` gate then keeps
    # failing against the stale bytes).
    fresh = {rel.removeprefix("icons/"): (ICONS_DIR / rel.removeprefix("icons/")).read_bytes() for rel in keep}
    refresh_drift_guard()
    for name, data in fresh.items():
        (ICONS_DIR / name).write_bytes(data)
    restore_binary_stubs_if_missing()
    print(
        "\nDone. Review `git status` and commit the regenerated icons (same 6 paths — content refreshed from logo.svg)."
    )


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check_committed_icons())
    main()
