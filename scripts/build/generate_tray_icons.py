"""Regenerate the committed Tauri tray state icons (repeatable).

``src-tauri/icons/tray/{idle,recording,transcribing,error}.png`` (+ the
macOS template source ``tray-mic-template.png``) are REAL committed
files, rendered from the app logo glyph (the logo WITHOUT its
background chip — per user decision the tray shows the icon itself) +
the shared state palette by
``voice_typer/client/scripts/generate-icons.mjs`` (the canonical icon
generator — edit the tray glyph / ``trayStateColors`` there to change
the icons). This script makes the tray-only regeneration repeatable
and self-validating in one command:

1. **Regenerate** — runs ``node generate-icons.mjs --tray`` (the mjs's
   tray-only mode), which writes exactly the 5 tray files into
   ``src-tauri/icons/tray/`` without touching the Electron / server /
   bundle-icon sets.

2. **Validate the PNGs** — every expected file must exist, carry the
   PNG magic, and be exactly 32x32 (the mjs's ``trayIconSize``). A
   future mjs change that alters the size / drops a state fails here
   instead of silently shipping a broken tray.

3. **Check the bundle wiring** — every Tauri config (base +
   per-arch) must declare the tray icons as the ``bundle.resources``
   string entry ``"icons/tray/"``. Tauri preserves the relative
   path, so the files land at ``$RESOURCE/icons/tray/<name>.png`` at
   runtime — exactly where ``src-tauri/src/tray.rs::load_tray_icon``
   looks. A config that drops the entry fails here.

4. **Refresh the drift guard** — re-runs
   ``tests/tauri/test_tray_icons.py`` (config wiring ↔ committed
   files ↔ Rust whitelist ↔ palette) so any drift fails immediately
   instead of on the next CI run.

Note: this is the TAURI tray pipeline. The pystray (Python-host)
tray assets live under ``voice_typer/server/assets/`` and are
generated by the full ``generate-icons.mjs`` run — do not mix the
two artifact sets.

Usage:
    python scripts/build/generate_tray_icons.py
"""

from __future__ import annotations

import json
import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SRC_TAURI = PROJECT_ROOT / "src-tauri"
TRAY_DIR = SRC_TAURI / "icons" / "tray"
MJS = PROJECT_ROOT / "voice_typer" / "client" / "scripts" / "generate-icons.mjs"

# The four logical state icons the Rust host whitelists
# (``src-tauri/src/tray.rs::is_allowed_icon_name`` / the
# ``ALLOWED_ICON_NAMES`` test constant) + the macOS template source
# (documented fallback — shipped but not loaded by the host today).
STATE_ICON_NAMES = ("idle", "recording", "transcribing", "error")
TEMPLATE_ICON_NAME = "tray-mic-template"
EXPECTED_FILES = (*STATE_ICON_NAMES, TEMPLATE_ICON_NAME)

# The ``bundle.resources`` entry that ships the tray icons: a plain
# string. Tauri copies string resources preserving their relative
# path, so ``icons/tray/*.png`` lands at ``$RESOURCE/icons/tray/`` —
# the path ``tray.rs`` reads. (A MAP entry can't be mixed into the
# string list — Tauri's ``BundleResources`` is an untagged enum:
# List-of-strings OR Map, never both.) Declared in the base config
# AND every per-arch config (per-arch ``--config`` merges replace the
# base resources array).
TRAY_RESOURCE_ENTRY = "icons/tray/"

# The drift-guard tests re-run after every regeneration.
DRIFT_TEST_NODES = ("tests/tauri/test_tray_icons.py",)

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
TRAY_ICON_SIZE = 32


def _png_dimensions(path: Path) -> tuple[int, int] | None:
    """Return ``(width, height)`` from the PNG IHDR, or ``None`` if the
    file is not a valid PNG (magic mismatch or truncated header)."""
    data = path.read_bytes()
    if not data.startswith(PNG_MAGIC):
        return None
    if len(data) < 24:
        return None
    # IHDR: 8-byte signature + 4-byte length + "IHDR" + 4-byte width +
    # 4-byte height (big-endian).
    if data[12:16] != b"IHDR":
        return None
    width, height = struct.unpack(">II", data[16:24])
    return width, height


def run_tray_generation(node: str = "node") -> None:
    """Run the mjs ``--tray`` mode (the canonical tray generator)."""
    if not MJS.is_file():
        sys.exit(f"icon generator not found: {MJS}")
    node_exe = shutil.which(node)
    if node_exe is None:
        sys.exit("node not found on PATH — install Node.js to regenerate tray icons.")
    base = [node_exe, str(MJS), "--tray"]
    # On Windows `npx`-style .cmd shims cannot be exec'd directly, but
    # node is a real .exe — still route through cmd.exe for symmetry
    # with generate_tauri_icons.py (harmless, deterministic on both).
    cmd: list[str] = ["cmd", "/c", *base] if os.name == "nt" else base
    result = subprocess.run(cmd, cwd=str(PROJECT_ROOT), capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"`generate-icons.mjs --tray` failed (exit {result.returncode}):\n{result.stdout}\n{result.stderr}")
    print(result.stdout.strip())


def validate_tray_files(tray_dir: Path = TRAY_DIR) -> None:
    """Every expected tray PNG must exist, be a real PNG, and be 32x32.

    ``missing`` = an expected state/template file absent after regen
    (the mjs dropped a state or renamed it — the Rust whitelist would
    then never find it at runtime). ``wrong_size`` = a file that is not
    a 32x32 PNG (a future mjs resize would silently change the tray
    rendering — fail fast instead).
    """
    missing = [n for n in EXPECTED_FILES if not (tray_dir / f"{n}.png").is_file()]
    if missing:
        sys.exit(f"tray icon generation incomplete — expected files missing under {tray_dir}: {missing}")
    wrong_size = []
    for name in EXPECTED_FILES:
        dims = _png_dimensions(tray_dir / f"{name}.png")
        if dims != (TRAY_ICON_SIZE, TRAY_ICON_SIZE):
            wrong_size.append(f"{name}.png={dims}")
    if wrong_size:
        sys.exit(f"tray icons must be {TRAY_ICON_SIZE}x{TRAY_ICON_SIZE} PNGs, got: " + ", ".join(wrong_size))
    print(f"Tray PNGs OK: {len(EXPECTED_FILES)} files, all {TRAY_ICON_SIZE}x{TRAY_ICON_SIZE} valid PNGs.")


def config_paths(root: Path = PROJECT_ROOT) -> list[Path]:
    """The base config + every per-arch config (sorted, deterministic).

    ``tauri.dev.conf.json`` (the dev-mode override, C-TDEV-1) is
    intentionally excluded: it is a minimal ``tauri dev`` overlay with
    no ``bundle`` section — dev builds reuse the base config's bundle —
    and is never merged by a CI ``--config`` per-arch build. This
    mirrors the same exclusion in ``tests/tauri/test_tray_icons.py``
    (``_all_tauri_configs``) so the script's wiring check and the
    drift-guard test agree.
    """
    per_arch = sorted(p for p in SRC_TAURI.glob("tauri.*.conf.json") if p.name != "tauri.dev.conf.json")
    return [SRC_TAURI / "tauri.conf.json", *per_arch]


def validate_resource_wiring(root: Path = PROJECT_ROOT) -> None:
    """Every Tauri config must declare ``TRAY_RESOURCE_MAP``.

    CI builds merge a per-arch config over the base (``--config
    tauri.<os>.conf.json`` replaces the resources array), so a map
    entry missing from ANY config means that platform ships no tray
    icons — ``load_tray_icon`` returns ``None`` and the tray never
    updates. Fail fast here rather than discovering it in a bundle.
    """
    problems = []
    for cfg in config_paths(root):
        data = json.loads(cfg.read_text(encoding="utf-8"))
        resources = data.get("bundle", {}).get("resources", [])
        if TRAY_RESOURCE_ENTRY not in resources:
            problems.append(
                f"{cfg.name}: bundle.resources is missing {TRAY_RESOURCE_ENTRY!r} (tray.rs reads $RESOURCE/icons/tray/)"
            )
    if problems:
        sys.exit("tray icon bundle wiring drift:\n  " + "\n  ".join(problems))
    print(f"Bundle wiring OK: {len(config_paths(root))} configs declare {TRAY_RESOURCE_ENTRY!r}.")


def refresh_drift_guard(root: Path = PROJECT_ROOT) -> None:
    """Re-run the tray drift-guard tests (exit non-zero on drift)."""
    cmd = [sys.executable, "-m", "pytest", "-q", "--no-cov", *DRIFT_TEST_NODES]
    result = subprocess.run(cmd, cwd=str(root), capture_output=True, text=True)
    print(result.stdout.strip())
    if result.returncode != 0:
        sys.exit(f"tray icon drift guard FAILED after regeneration:\n{result.stdout}\n{result.stderr}")


def main() -> None:
    run_tray_generation()
    validate_tray_files()
    validate_resource_wiring()
    refresh_drift_guard()
    print(
        "\nDone. Review `git status` and commit the regenerated tray icons "
        "(same 5 paths — content refreshed from the mjs tray section)."
    )


if __name__ == "__main__":
    main()
